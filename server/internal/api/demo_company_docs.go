const demoExpenseFAQ = `# 费用报销常见问题（示例）

> 星河科技财务部整理，示例内容。

## 出差

**问：当天往返能报住宿费吗？**
不能。住宿晚数按出差天数减一计算，当天往返不报住宿费（《差旅费管理办法》第五条）。

**问：住宿超标了怎么办？**
超出标准的部分个人承担，在报销单「个人承担金额」里写明，否则会被退回。经理及以上在一类城市的标准是每晚 700 元。

**问：打车能报吗？**
出差地的市内交通已经按每天 50 元包干，打车费不再另报；接待客户等特殊情况在报销单上说明原因，由部门负责人审批。

## 日常费用

**问：请客户吃饭怎么报？**
业务招待费需要事先在 OA 提交招待申请，人均不超过 300 元，发票抬头写公司全称。超过的部分需要销售总监审批。

**问：买办公用品能自己先垫付吗？**
500 元以下可以先垫付再报销，500 元以上请走采购流程。

## 打款

**问：报销多久到账？**
财务复核通过后 5 个工作日内打款到工资卡。每月 25 日之后提交的，可能顺延到下月初。

**问：报销被退回了在哪里看原因？**
费控系统「我的报销」里点单据，退回原因写在审批记录最下面。`

